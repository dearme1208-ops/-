export const TERMS = {
  /** 案件(projects)。「プロジェクト」とは書かない(Claudeモードの画面内も同じ) */
  project: "案件",
  /** 本日タブの作業一覧(dailyTasks)の総称。「日次タスク」とは書かない。1件ずつは「作業」 */
  dailyTasks: "本日の作業",
  /** 本日の作業・作業マスタ・実績の1件。「タスク」とは書かない */
  workItem: "作業",
  /** ToDoの1件。「タスク」はToDoの中だけで使う */
  todoItem: "タスク",
  /** 本日の作業・作業マスタ・実績・案件の分類欄(category)。「業務区分（大項目）」「大項目」「カテゴリ」とは書かない */
  category: "区分",
  /** ToDo自身の分類欄。区分とは別物なので、ToDoでは「区分」と書かない */
  todoCategory: "分類",
  /** ToDo・案件・段階を済ませること。段階にも「通過」とは書かない(登山・路線図テーマの比喩は除く) */
  complete: "完了",
  /** 計測中のタイマーを止めること(本日タブ) */
  stopTimer: "終了",
  /** 一覧から隠すことだけを指す。古いデータの書き出し＋削除は「古いデータの書き出しと削除」と呼ぶ */
  archive: "アーカイブ",
} as const;

